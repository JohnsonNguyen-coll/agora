import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await mkdir('data/qa', { recursive: true });
  await page.goto('http://localhost:5173/docs');
  await page.getByRole('heading', { name: 'A seat at the debate.' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'data/qa/docs-workspace-desktop.png' });
  await page.keyboard.press('Control+k');
  const dialog = page.getByRole('dialog', { name: 'Search documentation' });
  await dialog.waitFor();
  await dialog.getByRole('textbox').fill('configure your client');
  await dialog.getByRole('link', { name: /Configure your client/ }).click();
  await page.waitForURL('**/docs/mcp#configure-your-client');
  await page.getByRole('heading', { name: 'Configure your client', exact: true }).waitFor();
  assert.ok(await page.locator('#configure-your-client').evaluate(el => el.getBoundingClientRect().top >= 60));
  assert.ok((await page.locator('.docs-code').innerText()).includes('npm run configure:mcp'));
  await page.reload();
  await page.getByRole('heading', { name: 'Configure your client', exact: true }).waitFor();
  await page.getByRole('button', { name: /Search documentation/ }).click();
  await dialog.getByRole('textbox').fill('a-string-that-does-not-exist');
  await dialog.getByText(/No matching sections/).waitFor();
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: /Search documentation/ }).evaluate(el => el === document.activeElement), true);
  await page.getByRole('button', { name: /Search documentation/ }).click();
  await dialog.getByRole('textbox').fill('revocation');
  await page.keyboard.press('ArrowDown');
  assert.equal(await dialog.locator('a').first().evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Escape');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.goto('http://localhost:5173/docs');
    await page.getByRole('button', { name: /Guides/ }).click();
    await page.getByRole('navigation', { name: 'Documentation', exact: true }).getByRole('link', { name: 'Codex & Claude MCP', exact: true }).click();
    await page.getByRole('heading', { name: 'Bring the agent you use.' }).waitFor();
    assert.equal(await page.getByRole('button', { name: /Guides/ }).getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: 'data/qa/docs-workspace-' + width + '.png' });
    await page.goto('http://localhost:5173/');
    await page.locator('.hero-artwork img').waitFor();
    assert.equal(await page.locator('.hero-artwork img').evaluate(img => img.complete && img.naturalWidth > 0), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: 'data/qa/artwork-hero-' + width + '.png', fullPage: false });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://localhost:5173/');
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'data/qa/artwork-hero-desktop.png' });
  await page.getByRole('button', { name: 'Pause motion' }).click();
  assert.equal(await page.locator('.artwork-frame').evaluate(el => getComputedStyle(el).transform), 'none');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.artwork-frame').evaluate(el => getComputedStyle(el).transform), 'none');
  assert.deepEqual(errors, []);
  console.log('Docs search, anchors/reload, keyboard, mobile guides, artwork loading and reduced motion passed.');
} finally { await context.close(); await browser.close(); }
